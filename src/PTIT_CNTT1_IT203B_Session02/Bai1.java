//    Function<T, R> → T -> R (biến đổi dữ liệu)
//    Consumer<T> → T -> void (thực hiện hành động, không trả về)
//    Supplier<T> → () -> T (tạo / cung cấp giá trị, không cần đầu vào)

//    Kiểm tra xem một User có phải là Admin hay không (trả về true/false).
//    => Predicate<User>
//    <=> Nhận User - Trả về boolean

//    Chuyển đổi một đối tượng User thành một chuỗi String chứa thông tin username.
//    => Function<User, String>
//    <=> Nhận User - Trả về String

//    In thông tin chi tiết của User ra màn hình Console.
//    => Consumer<User>
//    <=> Nhận User - Ko trả giá trị, chỉ làm hành động

//    Khởi tạo một đối tượng User mới với các giá trị mặc định.
//    => Supplier<User>
//    <=> Không có đầu vào, trả về User


